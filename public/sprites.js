/* draw sprite: ctx, name, x (left), y (bottom baseline), scale, flip (face left), swap = {fromChar: color} */
function drawSprite(ctx, name, x, y, sc, flip, swap){
  var rows = SPR[name]; if (!rows) return;
  var h = rows.length, w = 0, i, j;
  for (i = 0; i < h; i++) if (rows[i].length > w) w = rows[i].length;
  for (i = 0; i < h; i++) {
    var row = rows[i];
    for (j = 0; j < row.length; j++) {
      var ch = row[j]; if (ch === '.') continue;
      var col = (swap && swap[ch]) || PAL[ch]; if (!col) continue;
      ctx.fillStyle = col;
      var px = flip ? x + (w - 1 - j) * sc : x + j * sc;
      ctx.fillRect(px, y - (h - i) * sc, sc, sc);
    }
  }
}
function spriteSize(name){ var rows = SPR[name], w = 0; for (var i = 0; i < rows.length; i++) if (rows[i].length > w) w = rows[i].length; return { w: w, h: rows.length }; }
